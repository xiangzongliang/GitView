<script setup lang="ts">
// Thin wrapper around @lucide/vue. The rest of the app references icons by
// short semantic names (e.g. "fetch", "stash") so swapping icon sets never
// touches consuming components.
import { computed, type Component } from "vue";
import {
	Archive,
	Bug,
	Check,
	Cherry,
	ChevronDown,
	ChevronRight,
	ChevronUp,
	CircleAlert,
	CircleCheck,
	Cloud,
	CloudDownload,
	Copy,
	Download,
	ExternalLink,
	Eye,
	EyeOff,
	FilePlus,
	FileText,
	Folder,
	FolderGit2,
	GitBranch,
	GitCommitHorizontal,
	GitGraph,
	GitMerge,
	Info,
	Maximize2,
	Minimize2,
	Minus,
	Moon,
	Palette,
	Pencil,
	Plus,
	RefreshCw,
	RotateCcw,
	Search,
	Settings,
	Sparkles,
	Sun,
	Tag,
	Terminal,
	Trash,
	TriangleAlert,
	Undo2,
	Upload,
	X,
} from "@lucide/vue";

const props = withDefaults(defineProps<{ name: string; size?: number }>(), {
	size: 14,
});

const map: Record<string, Component> = {
	bug: Bug,
	history: GitGraph,
	file: FileText,
	"file-plus": FilePlus,
	branch: GitBranch,
	merge: GitMerge,
	commit: GitCommitHorizontal,
	tag: Tag,
	cloud: Cloud,
	stash: Archive,
	fetch: CloudDownload,
	pull: Download,
	download: Download,
	push: Upload,
	refresh: RefreshCw,
	search: Search,
	plus: Plus,
	minus: Minus,
	"maximize-2": Maximize2,
	"minimize-2": Minimize2,
	folder: Folder,
	check: Check,
	x: X,
	"chevron-down": ChevronDown,
	"chevron-right": ChevronRight,
	"chevron-up": ChevronUp,
	trash: Trash,
	copy: Copy,
	alert: TriangleAlert,
	"alert-circle": CircleAlert,
	"check-circle": CircleCheck,
	reset: RotateCcw,
	restart: RotateCcw,
	cherry: Cherry,
	revert: Undo2,
	edit: Pencil,
	external: ExternalLink,
	terminal: Terminal,
	info: Info,
	eye: Eye,
	"eye-off": EyeOff,
	repo: FolderGit2,
	settings: Settings,
	sun: Sun,
	moon: Moon,
	palette: Palette,
	sparkles: Sparkles,
};

const icon = computed<Component>(() => map[props.name] || Info);
</script>

<template>
	<component :is="icon" :size="size" :stroke-width="1.9" aria-hidden="true" />
</template>
